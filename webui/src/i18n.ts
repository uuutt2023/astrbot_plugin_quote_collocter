export function t(ctx: BridgeContext | null, key: string, fallback = "", vars: Record<string, any> = {}): string {
  // 优先 i18n 文件
  const fromPlugin = tFromCtx(ctx, `pages.quote-gallery.${key}`) || tFromCtx(ctx, key);
  const base = fromPlugin || DICT[ctx?.locale as Locale]?.[key] || DICT["zh-CN"][key] || fallback || key;
  return base.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function formatBytes(bytes: number, locale: string = "zh-CN"): string {
  if (!bytes) return "0 B";
  const units = ["B", "KB", "MB", "GB", "TB"];
  let i = 0;
  let n = bytes;
  while (n >= 1024 && i < units.length - 1) { n /= 1024; i++; }
  if (locale === "zh-CN") return `${n.toFixed(n >= 100 || i === 0 ? 0 : 1)} ${units[i]}`;
  return `${n.toFixed(1)} ${units[i]}`;
}
